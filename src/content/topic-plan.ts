import type { Level } from "@/content/types";

export type PlannedTopic = {
  id: string;
  title: string;
  level: Level;
  focus: string;
  priority: "P0" | "P1" | "P2";
  sources: string;
};

export type TopicTrack = {
  code: string;
  name: string;
  description: string;
  sources: string;
  topics: PlannedTopic[];
};

const CORE = new Set([
  "BOT-01", "BOT-03", "GEN-01", "GEN-02", "ORG-01", "ORG-02", "PRO-01",
  "PRO-03", "PRO-06", "ROA-01", "ROA-02", "EXT-01", "EXT-02", "BRW-01",
  "BRW-02", "CAF-01", "CAF-03", "SEN-01", "SEN-02", "HLT-01", "HLT-02",
  "HIS-01", "HIS-02", "IND-01", "IND-02",
]);

function topics(
  rows: Array<[string, string, Level, string]>,
  sources: string,
): PlannedTopic[] {
  return rows.map(([id, title, level, focus], index) => ({
    id,
    title,
    level,
    focus,
    sources,
    priority: CORE.has(id) ? "P0" : index < 6 ? "P1" : "P2",
  }));
}

